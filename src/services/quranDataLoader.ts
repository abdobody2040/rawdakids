export function getLocalSurahWordData(surahId: number): any {
  const loader = SURAH_LOADERS[surahId];
  if (!loader) return null;
  try {
    const mod = loader();
    return mod && mod.default ? mod.default : mod;
  } catch (e) {
    console.warn('Error loading local surah ' + surahId, e);
    return null;
  }
}
